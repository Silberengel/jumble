/**
 * Regenerate nip66-cron/default-relays.mjs from relay preset arrays in src/constants.ts.
 * Run: node scripts/sync-nip66-default-relays.mjs
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const root = path.join(__dirname, '..')
const constantsPath = path.join(root, 'src/constants.ts')
const outPath = path.join(root, 'nip66-cron/default-relays.mjs')

const EXPORT_NAMES = [
  'DEFAULT_FAVORITE_RELAYS',
  'FAST_READ_RELAY_URLS',
  'NIP66_DISCOVERY_RELAY_URLS',
  'READ_ONLY_RELAY_URLS',
  'SOCIAL_KIND_BLOCKED_RELAY_URLS',
  'FAST_WRITE_RELAY_URLS',
  'GIF_RELAY_URLS',
  'SEARCHABLE_RELAY_URLS',
  'PROFILE_RELAY_URLS',
  'DEFAULT_NOSTRCONNECT_RELAY'
]

const src = fs.readFileSync(constantsPath, 'utf8')

function extractArray (name) {
  const re = new RegExp(`export const ${name}\\s*=\\s*\\[([\\s\\S]*?)\\]`, 'm')
  const m = src.match(re)
  if (!m) return []
  const urls = []
  for (const line of m[1].split('\n')) {
    const q = line.match(/['"](wss?:\/\/[^'"]+)['"]/)
    if (q) urls.push(q[1])
  }
  return urls
}

function normalizeRelayUrl (url) {
  try {
    const u = url.replace(/^ws:\/\//, 'wss://')
    const p = new URL(u.startsWith('wss://') ? u : `wss://${u}`)
    p.pathname = p.pathname.replace(/\/+/g, '/').replace(/\/$/, '') || '/'
    return p.toString()
  } catch {
    return url
  }
}

const seen = new Set()
const merged = []
for (const name of EXPORT_NAMES) {
  for (const raw of extractArray(name)) {
    if (!raw.startsWith('wss://') && !raw.startsWith('ws://')) continue
    const n = normalizeRelayUrl(raw)
    const key = n.toLowerCase()
    if (seen.has(key)) continue
    seen.add(key)
    merged.push(n)
  }
}

const body = `/** Generated by scripts/sync-nip66-default-relays.mjs — do not edit by hand. */
export const DEFAULT_RELAYS_TO_MONITOR = ${JSON.stringify(merged, null, 2)}
`

fs.writeFileSync(outPath, body)
console.log(`Wrote ${merged.length} relays to ${path.relative(root, outPath)}`)
